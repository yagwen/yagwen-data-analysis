import pandas as pd

# ---------- 练习 1：识别数据类型 ----------
# 思考：下面每一列分别是什么类型的数据？
# （答案见文件末尾）
dataset = pd.DataFrame({
    "学号": ["2026A001", "2026A002", "2026A003", "2026A004", "2026A005"],
    "专业": ["新闻", "广告", "新闻", "网新", "广告"],          # ?
    "年级": ["大一", "大一", "大二", "大一", "大二"],           # ?
    "月生活费(元)": [1500, 2000, 1800, 2500, 900],            # ?
    "每周刷短视频(小时)": [12, 5, 8, 20, 3],                  # ?
})

print("=== 练习数据 ===")
print(dataset)

# ---------- 练习 2：均值 vs 中位数（极端值的影响） ----------
# 普通班级成绩 vs 含极端值的班级成绩
normal = pd.Series([78, 85, 92, 66, 74, 88, 95, 60, 83, 71])
with_outlier = normal.copy()
with_outlier.iloc[0] = 10  # 某位同学考了 10 分（极端值）

print("\n=== 均值 vs 中位数：极端值的影响 ===")
print(f"原始数据     -> 均值: {normal.mean():.2f}, 中位数: {normal.median():.1f}")
print(f"含极端值数据 -> 均值: {with_outlier.mean():.2f}, 中位数: {with_outlier.median():.1f}")
print("观察：加入极端值后，均值被明显拉低，中位数几乎不变。")

# ---------- 练习 3：众数（定类数据的集中趋势） ----------
print("\n=== 专业分布（众数统计） ===")
print(dataset["专业"].value_counts())
print(f"众数: {dataset['专业'].mode()[0]}")

